class FakeLLM:
    def __init__(self, result=None, error=False):
        self.result = result or {"steps": ["Review the available information", "Prepare an introduction", "Contact the company"]}
        self.error = error
        self.inputs = []
        self.systems = []

    async def complete_json(self, system, user, schema):
        self.inputs.append(user)
        self.systems.append(system)
        if self.error:
            raise RuntimeError("model unavailable")
        return self.result


def setup_client(monkeypatch, features=(), llm=None):
    from fastapi.testclient import TestClient
    monkeypatch.setenv("CHAT_DB_PATH", ":memory:")
    backend_app.app.dependency_overrides[get_catalog] = lambda: MemoryCatalog(list(features))
    backend_app.app.dependency_overrides[get_graph] = lambda: MemoryGraph()
    backend_app.app.dependency_overrides[get_cala] = lambda: None
    backend_app.app.dependency_overrides[get_report_llm] = lambda: llm or FakeLLM()
    client = TestClient(backend_app.app)
    return client


def test_favorites_report_pdf_and_missing_ids(monkeypatch):
    feature = {"id": "acme", "name": "Acme <&>", "kinds": ["investor"], "description": "Fintech",
               "sectors": ["Fintech"], "sources": [{"name": "Cala", "url": "https://cala.test"}]}
    client = setup_client(monkeypatch, [feature])
    try:
        response = client.post("/api/favorites/report", json={"entity_ids": ["acme", "missing"]})
        assert response.status_code == 200
        assert response.content.startswith(b"%PDF")
        assert response.headers["x-favorites-not-included"] == "missing"
        doc = fitz.open(stream=response.content, filetype="pdf")
        text = "\n".join(page.get_text() for page in doc)
        assert all(term in text for term in ("Acme <&>", "Cala Match", "Proposed action plan",
                                               "Generated by Gemini from the Cala data above. Not Cala data.", "Data: Cala", "Not included"))
    finally:
        client.close()
        backend_app.app.dependency_overrides.clear()

