def test_report_preserves_request_order_and_catches_generic_load_errors(monkeypatch):
    client = setup_client(monkeypatch)
    async def fake_entity(entity_id, mode, session_id, catalog, graph, cala):
        if entity_id == "broken":
            raise RuntimeError("unexpected detail failure")
        await asyncio.sleep(0.03 if entity_id == "first" else 0)
        return {"id": entity_id, "name": entity_id.title(), "type": "startup", "facts": [], "rounds": [],
                "people": [], "portfolio": [], "why_match": []}
    original = api_routes.entity
    api_routes.entity = fake_entity
    try:
        response = client.post("/api/favorites/report", json={"entity_ids": ["first", "broken", "second"]})
        text = "\n".join(page.get_text() for page in fitz.open(stream=response.content, filetype="pdf"))
        assert response.status_code == 200
        assert text.index("First") < text.index("Second") < text.index("Not included")
        assert "broken: Cala request failed" in text
        assert response.headers["x-favorites-not-included"] == "broken"
    finally:
        api_routes.entity = original
        client.close()
        backend_app.app.dependency_overrides.clear()

