def test_rounds_and_other_sections_are_rendered_as_readable_text():
    details = {"name": "Readable", "type": "startup", "description": "Clear facts", "score": 90,
               "facts": [{"label": "Stage", "value": "Seed", "sources": [{"name": "Cala", "url": "https://cala.test", "date": "2026-11-14"}]}],
               "rounds": [{"round_type": "Seed", "amount": "€2m", "date": "2025", "leads": ["A"],
                           "investors": ["B"], "sources": [{"name": "Round source", "url": "https://cala.test/r"}]}],
               "people": [{"name": "Alex", "role": "Founder", "since": "2020", "sources": []}],
               "portfolio": [{"name": "Portfolio Co", "sources": []}],
               "why_match": [{"signal": "internal_sector", "text": "Sector match", "sources": [{"name": "Duplicate source", "url": "https://cala.test"}, {"name": "Why source", "url": "https://cala.test/w"}]}]}
    pdf = render_pdf([{"detail": details, "plan": ["Review the company"] * 3}], [], "raising",
                     datetime(2026, 11, 15, tzinfo=timezone.utc))
    text = "\n".join(page.get_text() for page in fitz.open(stream=pdf, filetype="pdf"))
    assert "15 November 2026" in text
    assert "Raising (investors to approach)" in text
    assert "Seed · €2m · 2025 · Leads: A · Investors: B" in text
    assert "Alex — Founder (since 2020)" in text and "Portfolio Co" in text and "Sector match" in text
    assert "internal_sector" not in text and "{" not in text
    assert "Round source" in text and "Why source" in text
    assert "[1] Cala — https://cala.test" in text and "[2] Round source — https://cala.test/r" in text
    assert "[3] Why source — https://cala.test/w" in text
    assert "[1]" in text and "[2]" in text and "[3]" in text
    assert text.index("Cala sources") < text.index("Generated by Gemini from the Cala data above. Not Cala data.")
    assert text.index("Review the company") > text.index("Generated by Gemini from the Cala data above. Not Cala data.")
    assert "14 November 2026" in text
    sources_section = text.split("Cala sources", 1)[1].split("Generated by Gemini", 1)[0]
    assert "Duplicate source" not in sources_section


