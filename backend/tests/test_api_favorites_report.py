def test_real_bii_fixture_sources_are_normalized_and_linked():
    fixture = Path(__file__).parent / "fixtures_entity_real_bii.json"
    detail = json.loads(fixture.read_text(encoding="utf-8"))
    pdf = render_pdf([{"detail": detail, "plan": None}], [], "raising", datetime(2026, 11, 15, tzinfo=timezone.utc))
    doc = fitz.open(stream=pdf, filetype="pdf")
    text = "\n".join(page.get_text() for page in doc)
    links = {link.get("uri") for page in doc for link in page.get_links() if link.get("uri")}
    assert "[1]" in text
    assert "3 dated 2026" in text
    assert "https://bii.dk" in text or "https://bii.dk" in links
    assert "theventurecodex.com" in text or any("theventurecodex.com" in url for url in links)
    entity_text = "\n".join(page.get_text() for page in doc if "Cala sources" in page.get_text())
    source_section = entity_text.split("Cala sources", 1)[1].split("Proposed action plan", 1)[0]
    assert "Not available in Cala" not in source_section
    assert "Cala sources cited in this report" in text


def test_every_fact_round_and_reason_line_has_at_most_three_references():
    detail = json.loads((Path(__file__).parent / "fixtures_entity_real_bii.json").read_text(encoding="utf-8"))
    sources, by_url = _source_catalog(detail)
    fact_html = _render_rows(detail["facts"], "data", by_url, sources)
    round_html = _round_rows(detail["rounds"], detail["name"], by_url, sources)
    why_html = _render_rows([{"text": "Affinity reason", "sources": detail["facts"][2]["sources"]}],
                            "why", by_url, sources)
    for row in re.findall(r"<li>(.*?)</li>", fact_html + round_html + why_html):
        assert len(re.findall(r"\[\d+\]", row)) <= 3
    assert all(re.search(r"\[\d+\]", content) for content in (fact_html, round_html, why_html))


def test_action_plan_block_is_kept_whole_after_long_entity_content():
    facts = [{"label": f"Fact {index}", "value": ("Detailed Cala data " * 35) + str(index), "sources": []}
             for index in range(24)]
